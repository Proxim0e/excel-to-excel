import re
import logging

logger = logging.getLogger(__name__)


def sanitize_filename(name: str) -> str:
    """
    Очищает строку, чтобы использовать её как имя файла или папки.
    Заменяет недопустимые символы на пробел.
    """
    if not name:
        return "unknown"

    # 1. Убираем запрещенные символы
    # Паттерн : * ? " < > |
    s = re.sub(r'[:\\/*?"<>|]', '', str(name))

    # 2. Убираем ВСЕ пробелы (включая пробелы между словами)
    # \s+ -> заменяет 1 или более пробелов на 1
    s = re.sub(r'\s+', ' ', s)

    # 3. Если длина > 120 — обрезаем до 115 и добавляем ".."
    if len(s) > 40:
        # Берем 115 символов и добавляем ".."
        ext = s[-4:]  # Берем последние 4 символа (расширение типа, например, ".pdf")
        s = s[:40] + ".." + ext

        # На случай, если в конце нет расширения
        if not ext:
            s = s[:40] + ".."


    return s if s else "unnamed"